// 各工位的 prompt 模板

// ① 动态注释（快模型）：根据行业为某个问题生成简短举例
export function annotatePrompt({ industry, question }) {
  return `你是企业老板身边的助手，帮他快速回忆起业务里的具体细节。

这个老板的行业是：${industry || "未知行业"}

现在有一个问题需要他填写，问题是：「${question}」

请你根据这个行业，给出 3~5 个这个问题的简短举例（每个举例 6~10 个字），帮他瞬间回忆起具体场景。

要求：
1. 举例要贴合这个行业的真实业务场景
2. 用简短短语，不要句子，不要序号，不要解释
3. 用中文顿号「、」分隔，直接输出举例

示例（假设行业是餐饮）：
服务员人手不够、外卖打包慢、后厨出餐排队`;
}

// ② 研判（慢模型）：判定缺口 + 初判候选方向
export function researchPrompt({ inputText }) {
  return `你是一位资深的企业 AI 架构研判员。请阅读一家企业的基本信息，做两件事：
1. 判断这些信息里，还缺哪些"对判断 AI 机会至关重要"的维度（缺口）；
2. 基于已有信息，结合行业常识，产出可能的 AI 机会候选方向。

企业信息如下：
${inputText}

关键维度共六个：
- 价值线（靠什么赚钱 / 降本 / 增效 / 抗风险）
- 断点线（哪个环节慢 / 乱 / 靠人 / 易错）
- 数据线（有什么数据留存）
- 系统线（用什么系统 / 工具）

请只输出一个 JSON，不要任何其他文字，格式：
{"缺口":["缺了哪些维度，例如：降本、抗风险"],"候选方向":["候选 AI 机会方向，例如：咨询转化、患者随访"]}

要求：
- "缺口"只列"对判断 AI 机会至关重要、但信息缺失"的维度；不相关的不列
- "候选方向"要包含两类：老板明确提到的方向 + 你基于行业常识发散的方向，共 4~6 个
- 候选方向要具体到业务环节（如"咨询转化"，而非笼统的"降本"）`;
}

// ③ 追问（慢模型）：三策略追问
export function questionPrompt({ inputText, research }) {
  return `你是一位经验丰富的访谈提问者，正在帮 AI 架构师向企业老板追问，以深化理解、发现更多机会。

企业信息：
${inputText}

上一轮分析结果：
- 信息缺口：${(research.gaps || []).join("、") || "无"}
- 候选机会方向：${(research.directions || []).join("、")}

请生成追问问题，分三种策略（最多 5 个，一次问完）：
1. 核实问（条件触发）：若企业信息有模糊、真假存疑处，追问确认
2. 下钻问（必须触发）：把"清楚但不深"的信息往下钻一层，问具体环节
3. 发散问（必须触发）：把候选方向抛给老板确认、补细节

要求：
- 问法口语化、不质问、不居高临下，用老板听得懂的话
- 每个问题配简要举例或选项引导，方便作答
- 追问要"换思路"，不重复原问题
- 问题彼此独立，不依赖先后

请只输出一个 JSON，不要其他文字，格式：
{"追问":[{"策略":"下钻","问题":"..."},{"策略":"发散","问题":"..."}]}`;
}

// ④ 定稿（慢模型）：产出 3-5 条可证伪假设
export function finalizePrompt({ inputText, answers, research }) {
  return `你是一位资深的企业 AI 架构师。请基于一家企业的完整信息，产出 3~5 条可证伪的 AI 机会假设。

企业信息：
${inputText}

老板对追问的补充回答：
${answers || "（未补充）"}

候选方向：
${(research?.directions || []).join("、")}

请产出 3~5 条假设，每条包含：
1. 分类：是"老板提到的方向"还是"老板可能没意识到的方向"
2. 陈述：用"若……则……"的可证伪句式
3. 先验证：进入企业后要先验证的关键问题（1~3 个，尽量具体到数字/环节）
4. 技术路径：如果假设成立可能用到的技术（如 RAG、工作流、图像生成等）

同时，请额外产出一个"维度关联图"（用于全局概览展示，抽象到维度级，不暴露具体假设），包含：
1. 业务维度：这家企业值得关注的业务环节/维度（5~8 个，用行业语言，如"获客转化""复诊管理"）
2. AI 能力：可能用到的 AI 能力标签（4~6 个，如"智能对话""流程自动化""图像生成"）
3. 关联：业务维度与 AI 能力的对应关系，带强度（强/中/弱）

请只输出一个 JSON，不要其他文字，格式：
{"假设":[{"分类":"...","陈述":"...","先验证":["..."],"技术路径":["..."]}],"维度图":{"业务维度":["..."],"AI能力":["..."],"关联":[{"业务":"...","AI":"...","强度":"强"}]}}`;
}

// ⑤ 校验（慢模型，挑刺）：角色线 + 合规线风险
export function verifyPrompt({ inputText, hypotheses }) {
  return `你是一位严格的质检员，专门给 AI 方案挑刺。现在有一批 AI 机会假设，请找出其中的风险和漏洞。

企业信息：
${inputText}

假设列表：
${JSON.stringify(hypotheses, null, 1)}

请从两个角度挑刺：
1. 角色线（采纳风险）：谁买单、谁使用、谁会抵触？使用者会不会不买账？有没有隐性阻力？
2. 合规线（红线风险）：涉及医疗/金融/隐私等监管吗？会不会踩红线？

请只输出一个 JSON，不要其他文字，格式：
{"风险":[{"假设":"针对哪条假设","类型":"采纳/合规","风险":"具体风险描述"}]}

要求：只挑真的有问题的，没有明显风险的假设不要硬凑。`;
}
